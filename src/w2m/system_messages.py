"""system_messages.py — the system message table FormatMessageW reads (Sprint 049, family "format message").

specs/system_messages.json holds every id from 0 to 16383 that FormatMessageW(FROM_SYSTEM | IGNORE_INSERTS, en-US)
answers on Windows Server 2025, build 26100 (probe format_message, run 38120951889): 4,493 messages, all ASCII. Server
2022 (build 20348, run 38120953179) answers 4,427 and words 109 of them otherwise; w2m's profile is build 26100
(BLACKBOARD, Sprint 049). `build_spec` writes the JSON from the stored run; `c_header` gives the guest runtime its
table (tools/guest_runtime/messages.c): the ids, each text's offset, and the texts as one byte string.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "specs" / "system_messages.json"
SOURCE_RUN = "38120951889"


def build_spec() -> dict[str, object]:
    rows = [json.loads(line) for line in (ROOT / "store" / "probe-runs" / SOURCE_RUN / "body-1.jsonl").read_text().splitlines()
            if line.startswith('{"s":"dump"')]
    spec: dict[str, object] = {"version": "0.1.0", "windows_build": "10.0.26100",
            "source": f"store/probe-runs/{SOURCE_RUN}/body-1.jsonl (probe format_message, rows \"dump\")",
            "messages": [[r["id"], r["text"]] for r in rows]}
    SPEC.write_text(json.dumps(spec, indent=0) + "\n")
    return spec


def messages() -> list[tuple[int, str]]:
    return [(i, t) for i, t in json.loads(SPEC.read_text())["messages"]]


def _c_string(text: str) -> str:
    out = []
    for c in text:
        o = ord(c)
        if c in '"\\?':
            out.append("\\" + c)
        elif 0x20 <= o < 0x7F:
            out.append(c)
        else:
            out.append(f"\\{o:03o}")
    return '"' + "".join(out) + '"'


def c_header() -> str:
    table = messages()
    if any(ord(c) > 0x7E for _, t in table for c in t):
        raise ValueError("a system message is not ASCII: messages.c widens bytes")
    offsets, at = [], 0
    for _, t in table:
        offsets.append(at)
        at += len(t)
    offsets.append(at)
    ids = ",".join(str(i) for i, _ in table)
    return (f"/* generated by src/w2m/system_messages.py from {SPEC.relative_to(ROOT)} */\n"
            f"#define W2M_MESSAGE_COUNT {len(table)}\n"
            f"static const unsigned short w2m_message_id[{len(table)}] = {{{ids}}};\n"
            f"static const unsigned int w2m_message_offset[{len(table) + 1}] = {{{','.join(map(str, offsets))}}};\n"
            f"static const char w2m_message_text[{at + 1}] =\n"
            + "\n".join(_c_string(t) for _, t in table) + ";\n")
