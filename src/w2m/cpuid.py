"""cpuid.py — the guest CPUID profile (specs/guest_cpuid.json; Sprint 040, review 2026-10-09 N5).

One table serves both executors: `lookup` for the model runtime, `c_header` for the guest runtime
in the VM, which compiles the same values into its image. A leaf the table lacks gets what the SDM
says a CPU returns for an input above its maximum: "the data for the highest basic information
leaf". A leaf with a fixed subleaf (leaf 7) answers only that subleaf; others ignore ECX.
"""

from __future__ import annotations

import json
from functools import cache
from pathlib import Path

SPEC = Path(__file__).resolve().parents[2] / "specs" / "guest_cpuid.json"


@cache
def _table() -> tuple[dict[tuple[int, int | None], tuple[int, int, int, int]], int, int]:
    spec = json.loads(SPEC.read_text())
    table = {(e["leaf"], e["subleaf"]): (e["eax"], e["ebx"], e["ecx"], e["edx"]) for e in spec["leaves"]}
    return table, table[(0, None)][0], table[(0x8000_0000, None)][0]


def lookup(eax: int, ecx: int) -> tuple[int, int, int, int]:
    """EAX, EBX, ECX, EDX for CPUID with these inputs (32-bit each)."""
    table, max_basic, max_ext = _table()
    leaf = eax & 0xFFFF_FFFF
    if leaf > max_ext or (max_basic < leaf < 0x8000_0000):
        leaf = max_basic
    if (leaf, ecx & 0xFFFF_FFFF) in table:
        return table[(leaf, ecx & 0xFFFF_FFFF)]
    if (leaf, None) in table:
        return table[(leaf, None)]
    if any(k[0] == leaf for k in table):                       # a subleaf the table does not list
        return 0, 0, 0, 0
    return table[(max_basic, None)] if (max_basic, None) in table else (0, 0, 0, 0)


def c_header() -> str:
    """The table as C for tools/guest_runtime (any_subleaf 1 where the spec's subleaf is null)."""
    table, max_basic, max_ext = _table()
    rows = ",\n".join(f"    {{0x{leaf:x}u, 0x{(sub or 0):x}u, {int(sub is None)}, 0x{a:x}u, 0x{b:x}u, 0x{c:x}u, 0x{d:x}u}}"
                      for (leaf, sub), (a, b, c, d) in table.items())
    return (f"/* generated by src/w2m/cpuid.py from specs/guest_cpuid.json; do not edit */\n"
            f"#define W2M_CPUID_MAX_BASIC 0x{max_basic:x}u\n#define W2M_CPUID_MAX_EXTENDED 0x{max_ext:x}u\n"
            f"static const struct {{ u32 leaf, subleaf, any_subleaf, eax, ebx, ecx, edx; }} w2m_cpuid_table[] = {{\n"
            f"{rows}\n}};\n")
