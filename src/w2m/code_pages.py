"""code_pages.py — the ANSI code page's tables for the guest runtime, from runner rows (Sprint 044).

tools/guest_runtime/code_pages.c answers GetStringTypeW, LCMapStringW and the 1252 conversions from
these tables. Every value is a row the probe probes/code_pages printed on Windows (run SOURCE_RUN,
whose rows the 15 other runs of the family repeat byte for byte; scripts/family_run.py, family
code_pages): per byte of code page 1252, its UTF-16 unit, CT_CTYPE1 class and upper and lower case;
and the 452 UTF-16 units outside the table that WideCharToMultiByte(1252) maps to a byte without the
default character (best fit).
"""

from __future__ import annotations

import json
from functools import cache
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SOURCE_RUN = "38043445987"


@cache
def rows() -> tuple[dict, ...]:
    path = ROOT / "store" / "probe-runs" / SOURCE_RUN / "body-1.jsonl"
    return tuple(json.loads(line) for line in path.read_text().splitlines() if line.strip())


def tables() -> tuple[list[int], list[int], list[int], list[int], list[tuple[int, int]]]:
    """(unit, ctype1, upper, lower) per byte, and best fit (unit, byte) sorted by unit."""
    by_byte = {int(r["s"][4:], 16): r for r in rows() if r["s"].startswith("acp.")}
    assert sorted(by_byte) == list(range(256))
    for r in by_byte.values():
        assert r["ret"] == 1 and min(r["ctype1"], r["upper_user"], r["lower_user"]) >= 0
        assert (r["upper_user"], r["lower_user"]) == (r["upper_invariant"], r["lower_invariant"])
    best = sorted((r["u"], r["byte"]) for r in rows() if r["s"] == "bestfit")
    assert all(r["ret"] == 1 and r["used_default"] == 0 for r in rows() if r["s"] == "bestfit")
    col = lambda k: [by_byte[b][k] for b in range(256)]    # noqa: E731
    return col("u"), col("ctype1"), col("upper_user"), col("lower_user"), best


def c_header() -> str:
    unit, ctype1, upper, lower, best = tables()

    def array(name: str, values: list[int]) -> str:
        body = ",".join(f"0x{v:x}" for v in values)
        return f"static const unsigned short {name}[{len(values)}] = {{{body}}};\n"

    pairs = ",".join(f"{{0x{u:x},0x{b:x}}}" for u, b in best)
    return (f"/* generated by src/w2m/code_pages.py from store/probe-runs/{SOURCE_RUN}/body-1.jsonl */\n"
            + array("w2m_ansi_unit", unit) + array("w2m_ansi_ctype1", ctype1)
            + array("w2m_ansi_upper", upper) + array("w2m_ansi_lower", lower)
            + f"#define W2M_BEST_FIT_COUNT {len(best)}\n"
            + f"static const struct {{ unsigned short unit, byte; }} w2m_best_fit[{len(best)}] = {{{pairs}}};\n")
