//! The headers the runtime's build writes, each byte for byte as the Python generator it carries wrote it (the image's
//! cache key covers their text, so a byte off here names another image).

use std::fs;
use std::path::Path;

use serde_json::Value;

fn read_json(path: &Path) -> Result<Value, String> {
    let text = fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))
}

fn u64_of(v: &Value, what: &str) -> Result<u64, String> {
    v.as_u64()
        .ok_or_else(|| format!("{what}: not an unsigned integer: {v}"))
}

/// One CPUID row: (leaf, subleaf or any), then EAX, EBX, ECX, EDX.
type CpuidRow = ((u64, Option<u64>), [u64; 4]);

/// `cpuid_table.h`: `src/w2m/cpuid.py` `c_header`, from `specs/guest_cpuid.json`.
pub fn cpuid(root: &Path) -> Result<String, String> {
    let spec = read_json(&root.join("specs/guest_cpuid.json"))?;
    let leaves = spec["leaves"].as_array().ok_or("specs/guest_cpuid.json: no leaves")?;
    // a dict keyed by (leaf, subleaf), in the spec's order (a later duplicate would keep the first's place)
    let mut rows: Vec<CpuidRow> = Vec::new();
    for e in leaves {
        let key = (u64_of(&e["leaf"], "leaf")?, e["subleaf"].as_u64());
        let regs = [
            u64_of(&e["eax"], "eax")?,
            u64_of(&e["ebx"], "ebx")?,
            u64_of(&e["ecx"], "ecx")?,
            u64_of(&e["edx"], "edx")?,
        ];
        match rows.iter_mut().find(|(k, _)| *k == key) {
            Some(row) => row.1 = regs,
            None => rows.push((key, regs)),
        }
    }
    let first = |key: (u64, Option<u64>)| {
        rows.iter()
            .find(|(k, _)| *k == key)
            .map(|(_, r)| r[0])
            .ok_or_else(|| format!("specs/guest_cpuid.json: no leaf {:#x}", key.0))
    };
    let (max_basic, max_ext) = (first((0, None))?, first((0x8000_0000, None))?);
    let body: Vec<String> = rows
        .iter()
        .map(|((leaf, sub), [a, b, c, d])| {
            format!(
                "    {{0x{leaf:x}u, 0x{:x}u, {}, 0x{a:x}u, 0x{b:x}u, 0x{c:x}u, 0x{d:x}u}}",
                sub.unwrap_or(0),
                u8::from(sub.is_none())
            )
        })
        .collect();
    Ok(format!(
        "/* generated by src/w2m/cpuid.py from specs/guest_cpuid.json; do not edit */\n\
         #define W2M_CPUID_MAX_BASIC 0x{max_basic:x}u\n#define W2M_CPUID_MAX_EXTENDED 0x{max_ext:x}u\n\
         static const struct {{ u32 leaf, subleaf, any_subleaf, eax, ebx, ecx, edx; }} w2m_cpuid_table[] = {{\n\
         {}\n}};\n",
        body.join(",\n")
    ))
}

/// The run `src/w2m/code_pages.py` reads (`SOURCE_RUN`).
const CODE_PAGE_RUN: &str = "38044229348";

/// `code_page_tables.h`: `src/w2m/code_pages.py` `c_header`, from the probe run's rows.
pub fn code_pages(root: &Path) -> Result<String, String> {
    let path = root.join(format!("store/probe-runs/{CODE_PAGE_RUN}/body-1.jsonl"));
    let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let rows: Vec<Value> = text
        .lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| serde_json::from_str(l).map_err(|e| format!("{}: {e}", path.display())))
        .collect::<Result<_, _>>()?;
    let mut by_byte: Vec<Option<&Value>> = vec![None; 256];
    for r in &rows {
        if let Some(hex) = r["s"].as_str().and_then(|s| s.strip_prefix("acp.")) {
            let b = usize::from_str_radix(hex, 16).map_err(|e| format!("{hex}: {e}"))?;
            *by_byte.get_mut(b).ok_or(format!("byte {b}"))? = Some(r);
        }
    }
    let col = |k: &str| -> Result<Vec<u64>, String> {
        by_byte
            .iter()
            .enumerate()
            .map(|(b, r)| u64_of(&r.ok_or(format!("no row for byte {b}"))?[k], k))
            .collect()
    };
    let (unit, ctype1, upper, lower) = (col("u")?, col("ctype1")?, col("upper_user")?, col("lower_user")?);
    let mut best: Vec<(u64, u64)> = rows
        .iter()
        .filter(|r| r["s"] == "bestfit")
        .map(|r| Ok((u64_of(&r["u"], "u")?, u64_of(&r["byte"], "byte")?)))
        .collect::<Result<_, String>>()?;
    best.sort();
    let array = |name: &str, values: &[u64]| {
        let body: Vec<String> = values.iter().map(|v| format!("0x{v:x}")).collect();
        format!(
            "static const unsigned short {name}[{}] = {{{}}};\n",
            values.len(),
            body.join(",")
        )
    };
    let pairs: Vec<String> = best.iter().map(|(u, b)| format!("{{0x{u:x},0x{b:x}}}")).collect();
    Ok(format!(
        "/* generated by src/w2m/code_pages.py from store/probe-runs/{CODE_PAGE_RUN}/body-1.jsonl */\n{}{}{}{}\
         #define W2M_BEST_FIT_COUNT {n}\n\
         static const struct {{ unsigned short unit, byte; }} w2m_best_fit[{n}] = {{{}}};\n",
        array("w2m_ansi_unit", &unit),
        array("w2m_ansi_ctype1", &ctype1),
        array("w2m_ansi_upper", &upper),
        array("w2m_ansi_lower", &lower),
        pairs.join(","),
        n = best.len()
    ))
}

/// `system_messages.py` `_c_string`: a C string literal, `"`, `\` and `?` escaped, printable ASCII kept, everything
/// else as a three-digit octal escape.
fn c_string(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        let o = c as u32;
        if c == '"' || c == '\\' || c == '?' {
            out.push('\\');
            out.push(c);
        } else if (0x20..0x7F).contains(&o) {
            out.push(c);
        } else {
            out.push_str(&format!("\\{o:03o}"));
        }
    }
    out.push('"');
    out
}

/// `system_messages.h`: `src/w2m/system_messages.py` `c_header`, from `specs/system_messages.json`.
pub fn system_messages(root: &Path) -> Result<String, String> {
    let spec = read_json(&root.join("specs/system_messages.json"))?;
    let messages = spec["messages"]
        .as_array()
        .ok_or("specs/system_messages.json: no messages")?;
    let mut table: Vec<(u64, &str)> = Vec::new();
    for m in messages {
        let text = m[1].as_str().ok_or("a message's text is not a string")?;
        if text.chars().any(|c| c as u32 > 0x7E) {
            return Err("a system message is not ASCII: messages.c widens bytes".to_string());
        }
        table.push((u64_of(&m[0], "message id")?, text));
    }
    let mut offsets = Vec::with_capacity(table.len() + 1);
    let mut at = 0;
    for (_, t) in &table {
        offsets.push(at);
        at += t.chars().count();
    }
    offsets.push(at);
    let ids: Vec<String> = table.iter().map(|(i, _)| i.to_string()).collect();
    let offsets: Vec<String> = offsets.iter().map(usize::to_string).collect();
    let texts: Vec<String> = table.iter().map(|(_, t)| c_string(t)).collect();
    Ok(format!(
        "/* generated by src/w2m/system_messages.py from specs/system_messages.json */\n\
         #define W2M_MESSAGE_COUNT {n}\n\
         static const unsigned short w2m_message_id[{n}] = {{{}}};\n\
         static const unsigned int w2m_message_offset[{}] = {{{}}};\n\
         static const char w2m_message_text[{}] =\n{};\n",
        ids.join(","),
        table.len() + 1,
        offsets.join(","),
        at + 1,
        texts.join("\n"),
        n = table.len()
    ))
}

/// `approximation_tables.h`: `src/w2m/approximate.py` `c_header`, from `specs/approximations.json`.
pub fn approximations(root: &Path) -> Result<String, String> {
    let spec = read_json(&root.join("specs/approximations.json"))?;
    let mut out = vec![
        "/* Generated by src/w2m/approximate.py from specs/approximations.json; not edited by hand. */".to_string(),
    ];
    for name in ["rcp", "rsqrt_even", "rsqrt_odd"] {
        let values: Vec<u64> = spec[name]
            .as_array()
            .ok_or(format!("specs/approximations.json: no {name}"))?
            .iter()
            .map(|v| u64_of(v, name))
            .collect::<Result<_, _>>()?;
        if values.len() < 4096 {
            return Err(format!(
                "specs/approximations.json: {name} has {} entries",
                values.len()
            ));
        }
        let rows: Vec<String> = values[..4096]
            .chunks(8)
            .map(|c| c.iter().map(|v| format!("0x{v:08x}u")).collect::<Vec<_>>().join(", "))
            .collect();
        out.push(format!(
            "static const u32 w2m_{name}[4096] = {{\n    {}\n}};",
            rows.join(",\n    ")
        ));
    }
    Ok(out.join("\n") + "\n")
}

