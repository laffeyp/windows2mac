"""gen_events.py — generate src/w2m/events.py from the current vocabulary (signals/current.json).

One frozen msgspec Struct per tag; the class name IS the tag, so substrate records the event
under the vocabulary's name (substrate kernel/sequencer.py: event_kind = type(obj).__name__).
Guest-plane tags are tagged Structs decoded from JSONL through the `GuestLine` union.

Usage:
    python3 scripts/gen_events.py            # write src/w2m/events.py
    python3 scripts/gen_events.py --check    # exit 1 if the committed file is stale
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VOCAB = ROOT / "signals" / (json.loads((ROOT / "signals" / "current.json").read_text())["version"] + ".json")
OUT = ROOT / "src" / "w2m" / "events.py"

# Vocabulary `types` -> annotation. `version` accepts major.minor[.patch]: the vocabulary's
# own version is major.minor (proposal P8, ratified into 0.2).
TYPE_ALIASES = {
    "sha256": 'Annotated[str, Meta(pattern=r"^sha256:[0-9a-f]{64}$")]',
    "id": "Annotated[str, Meta(min_length=1)]",
    "contract_id": 'Annotated[str, Meta(pattern=r"^[a-z0-9_]+(\\.[a-z0-9_]+)+$")]',
    "version": 'Annotated[str, Meta(pattern=r"^[0-9]+\\.[0-9]+(\\.[0-9]+)?$")]',
    "u64": "Annotated[int, Meta(ge=0)]",
    "i64": "Annotated[int, Meta(ge=-9223372036854775808, le=9223372036854775807)]",
    "float": "float",
    "bool": "bool",
    "text": "str",
    "js_u64": "Annotated[int, Meta(ge=0, le=9007199254740991)]",
    "js_i64": "Annotated[int, Meta(ge=-9007199254740991, le=9007199254740991)]",
}
ALIAS_NAME = {
    "sha256": "Sha256", "id": "Id", "contract_id": "ContractId", "version": "Version",
    "u64": "U64", "i64": "I64", "float": "float", "bool": "bool", "text": "str",
    "js_u64": "JsU64", "js_i64": "JsI64",
}
# Substrate canonicalizes harness-plane payloads with RFC 8785, which admits integers only in
# [-(2^53-1), 2^53-1] (substrate.api.canonical_bytes raises NonCanonicalValueError otherwise).
# Guest-plane lines are plain JSONL and keep the full 64-bit range. See proposals.json P8.
HARNESS_INT = {"u64": "js_u64", "i64": "js_i64"}


def _enum_alias(name: str) -> str:
    return "Enum" + "".join(part.capitalize() for part in name.split("_"))


def _annotation(ty: str, guest: bool) -> str:
    if ty.startswith("list<"):
        return f"tuple[{_annotation(ty[5:-1], guest)}, ...]"
    if ty.startswith("enum:"):
        return _enum_alias(ty[5:])
    return ALIAS_NAME[ty if guest else HARNESS_INT.get(ty, ty)]


def render(vocab_bytes: bytes) -> str:
    v = json.loads(vocab_bytes)
    digest = hashlib.sha256(vocab_bytes).hexdigest()
    out: list[str] = [
        f"# GENERATED by scripts/gen_events.py from signals/{v['version']}.json "
        f"(sha256:{digest}). Do not edit; regenerate.",
        '"""Typed events for vocabulary ' + v["version"] + ".",
        "",
        "Harness-plane classes are substrate event schemas: the class name is the tag. Guest-plane",
        "classes decode one JSONL trace line each through `GuestLine` (strict: unknown tags and",
        "extra fields fail). Construction does not check constraints; call `validate` before emit.",
        '"""',
        "",
        "# ruff: noqa: N801, E501",
        "from __future__ import annotations",
        "",
        "from typing import Annotated, Literal, TypeVar",
        "",
        "import msgspec",
        "from msgspec import Meta, Struct",
        "",
        f'VOCAB_VERSION = "{v["version"]}"',
        f'VOCAB_SHA256 = "sha256:{digest}"',
        "GUEST_PLANE_VERSIONS: tuple[str, ...] = ("
        + "".join(f'"{x}", ' for x in v.get("guest_plane_compatible_versions", [v["version"]]))
        + ")",
        "",
    ]
    for key, expr in TYPE_ALIASES.items():
        if ALIAS_NAME[key] not in ("float", "bool", "str"):
            out.append(f"{ALIAS_NAME[key]} = {expr}")
    out.append("")
    for name, values in v["enums"].items():
        out.append(f"{_enum_alias(name)} = Literal[{', '.join(repr(x) for x in values)}]")
    out.append("")

    harness: list[str] = []
    guest: list[str] = []
    for t in v["tags"]:
        is_guest = t["category"] == "guest"
        (guest if is_guest else harness).append(t["name"])
        cfg = "frozen=True, forbid_unknown_fields=True"
        if is_guest:
            cfg += f', tag="{t["name"]}", tag_field="tag"'
        out.append("")
        out.append(f"class {t['name']}(Struct, {cfg}):")
        out.append(f'    """{t["category"]} / {t["stratum"]}. {t["note"]}"""')
        out.append("")
        for f in t["payload"]:
            out.append(f"    {f}: {_annotation(t['types'][f], is_guest)}")
        for f in t.get("optional_payload", []):
            out.append(f"    {f}: {_annotation(t['types'][f], is_guest)} | None = None")
        out.append("")
    out += [
        "",
        f"HARNESS_EVENTS: tuple[type[Struct], ...] = ({', '.join(harness)},)",
        f"GUEST_EVENTS: tuple[type[Struct], ...] = ({', '.join(guest)},)",
        f"GuestLine = {' | '.join(guest)}",
        "",
        '_S = TypeVar("_S", bound=Struct)',
        "",
        "",
        "def validate(obj: _S) -> _S:",
        '    """Return `obj` if every field satisfies its declared type and constraints.',
        "",
        "    Raises msgspec.ValidationError naming the failing field path. This is the",
        "    speaker's-mouth check (grammar/PRINCIPLES.md commitment 2); msgspec does not",
        "    check constraints at construction.",
        '    """',
        "    msgspec.convert(msgspec.to_builtins(obj), type(obj))",
        "    return obj",
        "",
        "",
        "_GUEST_DECODER: msgspec.json.Decoder[GuestLine] = msgspec.json.Decoder(GuestLine)",
        "",
        "",
        "def decode_guest_line(line: bytes | str) -> GuestLine:",
        '    """Decode and validate one guest-trace JSONL line; raises msgspec.ValidationError."""',
        "    return _GUEST_DECODER.decode(line)",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    text = render(VOCAB.read_bytes())
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"stale: {OUT} differs from a fresh generation; run scripts/gen_events.py",
                  file=sys.stderr)
            return 1
        print(f"{OUT}: up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
