"""gen_decoder.py — generate src/w2m/x86dec_tables.py from specs/x86_decode.json.

The spec is the authored artifact (Intel SDM opcode maps, cited per entry); the tables module is
derived and never hand-edited. `--check` exits 1 when the committed tables are stale.

Usage: python3 scripts/gen_decoder.py [--check]
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "specs" / "x86_decode.json"
OUT = ROOT / "src" / "w2m" / "x86dec_tables.py"


def render(raw: bytes) -> str:
    spec = json.loads(raw)
    digest = hashlib.sha256(raw).hexdigest()
    table: dict[tuple[str, int, bool], list[tuple[object, ...]]] = {}
    for e in spec["entries"]:
        key = (e["map"], e["op"], bool(e.get("vex", False)))
        sizes = tuple(sorted(e["sizes"].items())) if "sizes" in e else None
        table.setdefault(key, []).append(
            (e["pfx"], e.get("reg"), e["modrm"], e.get("imm"), e["mn"], sizes, e.get("mod"), e.get("w")))
    lines = [
        f"# GENERATED by scripts/gen_decoder.py from specs/x86_decode.json "
        f"(spec {spec['version']}, sha256:{digest}). Do not edit; regenerate.",
        '"""Decode tables: (map, opcode, vex) -> entries of',
        "(mandatory_prefix, modrm_reg, has_modrm, immediate, mnemonic, sizes, modrm_byte, rex_w).\"\"\"",
        "",
        "# ruff: noqa: E501",
        f'SPEC_VERSION = "{spec["version"]}"',
        f'SPEC_SHA256 = "sha256:{digest}"',
        f"LOCKABLE = frozenset({sorted(spec['prefixes']['lockable'])!r})",
        f"REP_STRING = frozenset({sorted(spec['prefixes']['rep_string'])!r})",
        "Entry = tuple[str, int | None, bool, str | None, str, tuple[tuple[str, str], ...] | None, str | None, int | None]",
        "TABLE: dict[tuple[str, int, bool], tuple[Entry, ...]] = {",
    ]
    for key in sorted(table):
        lines.append(f"    {key!r}: {tuple(table[key])!r},")
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render(SPEC.read_bytes())
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"stale: {OUT}; run scripts/gen_decoder.py", file=sys.stderr)
            return 1
        print(f"{OUT}: up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
