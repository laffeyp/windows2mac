"""gen_decoder.py — generate src/w2m/x86dec_tables.py from specs/x86_decode.json.

The spec is the authored artifact (Intel SDM opcode maps, cited per entry); the tables module is
derived and never hand-edited. `--check` exits 1 when the committed tables are stale.

Usage: python3 scripts/gen_decoder.py [--check]
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "specs" / "x86_decode.json"
OUT = ROOT / "src" / "w2m" / "x86dec_tables.py"


def render(raw: bytes) -> str:
    spec = json.loads(raw)
    digest = hashlib.sha256(raw).hexdigest()
    table: dict[tuple[str, int, str], list[tuple[object, ...]]] = {}
    seen: dict[str, int] = {}
    for idx, e in enumerate(spec["entries"]):
        h = json.dumps(e, sort_keys=True)
        if h in seen:
            raise SystemExit(f"spec row {idx} duplicates row {seen[h]}: {e['mn']}")
        seen[h] = idx
        enc = ("evex" if e.get("evex") else "xop" if e.get("xop") else
               "vex" if e.get("vex") else "legacy")
        key = (e["map"], e["op"], enc)
        sizes = tuple(sorted(e["sizes"].items())) if "sizes" in e else None
        isizes = tuple(sorted(e["iclass_sizes"].items())) if "iclass_sizes" in e else None
        table.setdefault(key, []).append(
            (e["pfx"], e.get("reg"), e["modrm"], e.get("imm"), e["mn"], sizes, e.get("mod"), e.get("w"),
             e.get("l"), e.get("form"), e["iclass"], isizes, e.get("requires"),
             (e["fallback"]["mn"], e["fallback"]["iclass"]) if "fallback" in e else None,
             bool(e.get("lock")), e.get("vvvv"), e.get("ops"), e.get("opsize64"),
             "sha256:" + hashlib.sha256(h.encode()).hexdigest(),    # row identity, as confirmations
             e.get("np") or False,                                    # SDM NP (True) or NFx ("nfx")
             tuple(e["reg_valid"]) if "reg_valid" in e else None))     # ModRM.reg values that exist
    lines = [
        "# SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0",
        "# Copyright (C) 2026 Peter Laffey",
        f"# GENERATED by scripts/gen_decoder.py from specs/x86_decode.json "
        f"(spec {spec['version']}, sha256:{digest}). Do not edit; regenerate.",
        '"""Decode tables: (map, opcode, encoding class) -> entries of (mandatory_prefix, modrm_reg, has_modrm,',
        "immediate, mnemonic, sizes, modrm_byte, rex_w, vex_l, form, iclass, iclass_sizes, requires,",
        "fallback(mnemonic, iclass), lock_ok, vvvv, operand_template, opsize64, row_sha256, np, reg_valid).\"\"\"",
        "",
        "# ruff: noqa: E501",
        f'SPEC_VERSION = "{spec["version"]}"',
        f'SPEC_SHA256 = "sha256:{digest}"',
        f"LOCKABLE = frozenset({sorted(spec['prefixes']['lockable'])!r})",
        f"REP_STRING = frozenset({sorted(spec['prefixes']['rep_string'])!r})",
        f"REPE_STRING = frozenset({sorted(spec['prefixes'].get('repe_string', []))!r})",
        f"LEGACY_PREFIX_OPCODES: dict[tuple[str, int], tuple[str, ...]] = {dict(sorted((tuple(x['opcode']), tuple(x['legacy'])) for x in spec['prefixes'].get('legacy_prefix_opcodes', [])))!r}",
        "Sizes = tuple[tuple[str, str], ...] | None",
        "Entry = tuple[str, int | None, bool, str | None, str, Sizes, str | None, int | None, int | None, str | None, str, Sizes, str | None, tuple[str, str] | None, bool, str | None, str | None, str | None, str, bool | str, tuple[int, ...] | None]",
        "TABLE: dict[tuple[str, int, str], tuple[Entry, ...]] = {",
    ]
    for key in sorted(table):
        lines.append(f"    {key!r}: {tuple(table[key])!r},")
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render(SPEC.read_bytes())
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"stale: {OUT}; run scripts/gen_decoder.py", file=sys.stderr)
            return 1
        print(f"{OUT}: up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
